export function translateFrenchUiText(value: string) {
  const trimmed = value.trim();
  if (!trimmed) return value;

  const exact = exactTranslations.get(trimmed);
  if (exact) {
    return value.replace(trimmed, exact);
  }

  let translated = trimmed;
  for (const [pattern, replacement] of phraseTranslations) {
    translated = translated.replace(pattern, replacement);
  }

  return translated === trimmed ? value : value.replace(trimmed, translated);
}

export function hasFrenchRuntimeTranslation(value: string) {
  return translateFrenchUiText(value) !== value;
}
