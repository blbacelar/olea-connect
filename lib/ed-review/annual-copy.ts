const numbered: Record<string, string> = {
  Competency: "Compétence", Goal: "Objectif", Milestone: "Jalon", Activity: "Activité", Action: "Action",
};

export function annualText(locale: string, value: string): string {
  if (locale !== "fr-CA") return value;
  const match = /^(Competency|Goal|Milestone|Activity|Action) (\d+)$/.exec(value);
  if (match) return `${numbered[match[1]]} ${match[2]}`;
  return french[value] ?? value;
}

export function annualFieldValue(locale: string, value: string, sourceDefault?: string): string {
  return sourceDefault !== undefined && value === sourceDefault
    ? annualText(locale, value)
    : value;
}
